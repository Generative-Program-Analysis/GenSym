#!/usr/bin/env python3

import argparse
import csv
import difflib
import statistics
import sys
from collections import Counter
from pathlib import Path


HERE = Path(__file__).resolve().parent


DEFAULT_SUMMARIES = (
    ("btree", "final_results_btree.compilation.csv"),
    ("Collection-C", "final_results_Collection-C.compilation.csv"),
    ("quicksort", "final_results_quicksort.compilation.csv"),
    ("evaluator", "final_results_evaluator.compilation.csv"),
)

SPEEDUP_COLUMNS = {
    "Default": "T_GenWasym_NoConfig_instr_exec(s)",
    "Snapshot": "T_GenWasym_Snapshot_instr_exec(s)",
    "CostModel": "T_GenWasym_CostModel_instr_exec(s)",
}

COLLECTION_SPEEDUP_COLUMNS = {
    "Default": "T_GenWasym_noreuse_exec(s)",
    "Snapshot": "T_GenWasym_snapshot_exec(s)",
    "CostModel": "T_GenWasym_heuristic_exec(s)",
}

RELATIVE_SPEEDUP_COLUMNS = {
    "Snapshot/Default": ("Default", "Snapshot"),
    "CostModel/Default": ("Default", "CostModel"),
}


def main() -> int:
    parser = argparse.ArgumentParser(
        description=(
            "Compute the average speedup across compilation summary CSVs. "
            "With no paths, use btree, Collection-C, quicksort, and evaluator."
        )
    )
    parser.add_argument(
        "summary_csv",
        type=Path,
        nargs="*",
        help="Optional compilation summary CSVs generated by summary.py.",
    )
    parser.add_argument(
        "--metric",
        choices=tuple(SPEEDUP_COLUMNS),
        help="Compute only this speedup instead of all three.",
    )
    parser.add_argument(
        "--benchmark",
        action="append",
        default=[],
        help="Benchmark or module name to include; repeatable.",
    )
    parser.add_argument(
        "--cutoff",
        action="append",
        default=[],
        help="Benchmark or module name to exclude as a cutoff case; repeatable.",
    )
    args = parser.parse_args()

    if args.summary_csv:
        summaries = [(path.stem, path) for path in args.summary_csv]
    else:
        summaries = [(suite, HERE / filename) for suite, filename in DEFAULT_SUMMARIES]

    requested = set(args.benchmark)
    timed_out = set(args.cutoff)
    values: dict[str, list[tuple[str, str, float]]] = {
        label: [] for label in SPEEDUP_COLUMNS
    }
    relative_values: dict[str, list[tuple[str, str, float]]] = {
        label: [] for label in RELATIVE_SPEEDUP_COLUMNS
    }
    loaded_summaries: list[tuple[str, Path, list[dict[str, str]]]] = []
    available_benchmarks: set[str] = set()
    for suite, summary_csv in summaries:
        if not summary_csv.is_file():
            print(f"Summary CSV not found: {summary_csv}", file=sys.stderr)
            return 2

        with summary_csv.open(newline="", encoding="utf-8") as handle:
            rows = list(csv.DictReader(handle))
        loaded_summaries.append((suite, summary_csv, rows))
        available_benchmarks.update(
            row.get("Benchmark") or row.get("Module") or "<unnamed>"
            for row in rows
        )

    invalid_cutoffs = sorted(timed_out - available_benchmarks)
    if invalid_cutoffs:
        print("Invalid --cutoff value(s): " + ", ".join(invalid_cutoffs), file=sys.stderr)
        missing_suggestion = False
        for cutoff in invalid_cutoffs:
            suggestions = difflib.get_close_matches(
                cutoff, sorted(available_benchmarks), n=3, cutoff=0.4
            )
            if suggestions:
                print(
                    f"  {cutoff!r} not found. Did you mean: "
                    + ", ".join(repr(value) for value in suggestions)
                    + "?",
                    file=sys.stderr,
                )
            else:
                missing_suggestion = True
        if missing_suggestion:
            print("Valid --cutoff options:", file=sys.stderr)
            for benchmark in sorted(available_benchmarks):
                print(f"  {benchmark}", file=sys.stderr)
        return 2

    for suite, summary_csv, rows in loaded_summaries:

        columns = rows[0].keys() if rows else ()
        if "T_WASP_exec(s)" in columns:
            baseline_column = "T_WASP_exec(s)"
            time_columns = COLLECTION_SPEEDUP_COLUMNS
        else:
            baseline_column = "T_WASP_instr_exec(s)"
            time_columns = SPEEDUP_COLUMNS
        selected_metrics = [args.metric] if args.metric else list(time_columns)

        for row in rows:
            benchmark = row.get("Benchmark") or row.get("Module") or "<unnamed>"
            if requested and benchmark not in requested:
                continue
            if benchmark in timed_out:
                continue
            try:
                baseline = float(row.get(baseline_column, ""))
            except ValueError:
                print(
                    f"Invalid {baseline_column} for {suite}/{benchmark}",
                    file=sys.stderr,
                )
                return 1
            if baseline <= 0:
                print(f"Invalid non-positive WASP baseline for {suite}/{benchmark}", file=sys.stderr)
                return 1

            for label in selected_metrics:
                metric = time_columns[label]
                raw_value = row.get(metric, "")
                if not raw_value:
                    print(f"Missing {metric} for {suite}/{benchmark}", file=sys.stderr)
                    return 1
                try:
                    genwasym_time = float(raw_value)
                except ValueError:
                    print(
                        f"Invalid {metric} for {suite}/{benchmark}: {raw_value!r}",
                        file=sys.stderr,
                    )
                    return 1
                if genwasym_time <= 0:
                    print(f"Invalid non-positive GenWasym time for {suite}/{benchmark}", file=sys.stderr)
                    return 1
                values.setdefault(label, []).append(
                    (suite, benchmark, baseline / genwasym_time)
                )

            for label, (numerator_label, denominator_label) in RELATIVE_SPEEDUP_COLUMNS.items():
                numerator_column = time_columns[numerator_label]
                denominator_column = time_columns[denominator_label]
                try:
                    numerator = float(row.get(numerator_column, ""))
                    denominator = float(row.get(denominator_column, ""))
                except ValueError:
                    print(
                        f"Missing or invalid relative-speedup inputs for {suite}/{benchmark}: "
                        f"{numerator_column}, {denominator_column}",
                        file=sys.stderr,
                    )
                    return 1
                if numerator <= 0 or denominator <= 0:
                    print(
                        f"Invalid non-positive relative-speedup input for {suite}/{benchmark}",
                        file=sys.stderr,
                    )
                    return 1
                relative_values[label].append(
                    (suite, benchmark, numerator / denominator)
                )

    active_values = {
        label: items for label, items in values.items() if items
    }
    active_relative_values = {
        label: items for label, items in relative_values.items() if items
    }
    if not active_values and not active_relative_values:
        print("No benchmarks selected.", file=sys.stderr)
        return 1

    print("Average speedups across all selected benchmark rows:")
    for label, items in active_values.items():
        average = statistics.fmean(value for _, _, value in items)
        geomean = statistics.geometric_mean(value for _, _, value in items)
        counts = Counter(suite for suite, _, _ in items)
        count_text = ", ".join(
            f"{suite}: {count}"
            for suite, count in sorted(counts.items())
        )
        print(
            f"  {label}: arithmetic mean={average:.1f}x, "
            f"geomean={geomean:.1f}x ({len(items)} data points; {count_text})"
        )
    print("Relative GenWasym speedups:")
    for label, items in active_relative_values.items():
        average = statistics.fmean(value for _, _, value in items)
        geomean = statistics.geometric_mean(value for _, _, value in items)
        counts = Counter(suite for suite, _, _ in items)
        count_text = ", ".join(
            f"{suite}: {count}"
            for suite, count in sorted(counts.items())
        )
        print(
            f"  {label}: arithmetic mean={average:.1f}x, "
            f"geomean={geomean:.1f}x ({len(items)} data points; {count_text})"
        )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
